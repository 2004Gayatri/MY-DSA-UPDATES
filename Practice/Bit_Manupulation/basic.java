import java.util.*;
public class basic{
    public static void main(String[]args){
        // AND OPERATOR
        int ans = 5 & 6;
        System.out.println("answer of AND Operation for 5 and 6 is " + ans);

        //OR OPERATOR
         int ans1 = 5 | 6;
        System.out.println("answer of OR Operation for 5 and 6 is " + ans1);

        //XOR OPERATOR 

        int ans2 = 5 ^ 6;
        System.out.println("answer of XOR Operation for 5 and 6 is " + ans2);


        // Binary Left Shift
        System.out.println("answer of Binary left shift Operation for 5 and 2 is " + (5<<2));

        //Binary Right Shift
         
        System.out.println("answer of Binary Right Shift Operation for 6 and 1 is " + (6>>1));

    }
}